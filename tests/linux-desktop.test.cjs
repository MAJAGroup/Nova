const { test } = require('node:test');
const assert = require('node:assert/strict');
const { mkdtemp, readFile, writeFile, mkdir, access, rm } = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { registerLinuxDesktop } = require('../linux-desktop');

test('Linux desktop registration preserves the icon and uses a stable identity and safely quoted launch path', async () => {
  const dataHome = await mkdtemp(path.join(os.tmpdir(), 'nova-desktop-'));
  const iconPath = path.resolve('assets/icon.png');
  try {
    const installed = await registerLinuxDesktop({ dataHome, iconPath, executable: '/tmp/My Browser/Nova%ready.AppImage', args: ['--appimage-extract-and-run'] });
    assert.deepEqual(await readFile(installed.iconPath), await readFile(iconPath));
    let entry = await readFile(installed.desktopFile, 'utf8');
    assert.match(entry, /^StartupWMClass=edu\.buffalo\.nova$/m);
    assert.match(entry, /^Exec="\/tmp\/My Browser\/Nova%%ready\.AppImage" "--appimage-extract-and-run" %U$/m);
    assert.ok(entry.includes('Icon=' + installed.iconPath));
    const updated = await registerLinuxDesktop({ dataHome, iconPath, executable: '/new/place/electron', args: ['/projects/nova'] });
    assert.equal(updated.desktopFile, installed.desktopFile);
    entry = await readFile(installed.desktopFile, 'utf8');
    assert.match(entry, /^Exec="\/new\/place\/electron" "\/projects\/nova" %U$/m);
    assert.ok(!entry.includes('My Browser'));
  } finally { await rm(dataHome, { recursive: true, force: true }); }
});

test('Nova replaces the desktop entry generated by an earlier version', async () => {
  const dataHome=await mkdtemp(path.join(os.tmpdir(),'nova-desktop-upgrade-'));
  try {
    const oldEntry=path.join(dataHome,'applications','edu.buffalo.orbit.desktop');
    await mkdir(path.dirname(oldEntry),{recursive:true});
    await writeFile(oldEntry,'[Desktop Entry]\nName=ORBIT\nComment=Explore the web in your own universe\nStartupWMClass=edu.buffalo.orbit\n');
    const installed=await registerLinuxDesktop({dataHome,iconPath:path.resolve('assets/icon.png'),executable:'/tmp/Nova.AppImage'});
    assert.equal(path.basename(installed.desktopFile),'edu.buffalo.nova.desktop');
    assert.match(await readFile(installed.desktopFile,'utf8'),/^Name=Nova$/m);
    await assert.rejects(access(oldEntry),{code:'ENOENT'});
  } finally {await rm(dataHome,{recursive:true,force:true});}
});
